# This part is the part that makes Fig 2 (and 4)
all_results_thinned_rmse_logit <- all_results %>%
  group_by(UID) %>%
  slice_min(order_by = RMSE.logit, n = 1000, with_ties = FALSE)

abc_summary <- all_results_thinned_rmse_logit %>%
  group_by(UID) %>%
  summarise(SE = sd(R0)/sqrt(length(R0)),
            R0 = mean(R0)) 
res <- rma(yi = R0, sei = SE, method = "REML", data = abc_summary)
# Extract estimated population mean (mu) and between-UID tau
mu_hat  <- as.numeric(coef(res))     # population mean
tau_hat <- sqrt(res$tau2)            # between-UID SD

# For each farm UID we remove that from the estimation of a global R0 and then use the estimated R0 value to simulate multiple OPA trajectories.
